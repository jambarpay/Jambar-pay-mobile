      final messages = <String>[
        loc.appTitle,
        loc.chooseLanguage,
        loc.french,
        loc.english,
        loc.languageChangedFrench,
        loc.languageChangedEnglish,
        loc.contactSupport,
        loc.email,
        loc.phone,
        loc.ok,
        loc.secretCodeChanged,
        loc.logout,
        loc.logoutConfirm,
        loc.cancel,
        loc.logoutButton,
        loc.darkMode,
        loc.lightMode,
        loc.changeSecretCode,
        loc.back,
        loc.home,
        loc.history,
        loc.restaurants,
        loc.profile,
        loc.accountPage,
        loc.enterAmountToPay,
        loc.availableBalanceTitle,
        loc.availableBalance('1 000 Fcfa'),
        loc.amount,
        loc.pay,
        loc.invalidAmount,
        loc.insufficientBalance,
        loc.paymentSuccess,
        loc.paymentSuccessBody('1 000 Fcfa', 'Le FOOD'),
        loc.finish,
        loc.retry,
        loc.noTransactionsAvailable,
        loc.noRestaurantsAvailable,
        loc.noTransactionsMatchSearch,
        loc.filterAll,
        loc.filterToday,
        loc.filterThisWeek,
        loc.filterThisMonth,
        loc.searchTransactions,
        loc.statusPending,
        loc.statusValidated,
        loc.statusFailed,
        loc.dateToday,
        loc.dateYesterday,
        loc.recentTransactions,
        loc.viewAll,
        loc.map,
        loc.list,
        loc.restaurantsNearby(1),
