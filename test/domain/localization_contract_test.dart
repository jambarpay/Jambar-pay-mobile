        loc.paymentConfirmedBody('Le FOOD'),
        loc.balanceUpdated,
        loc.walletSynced,
        loc.employerTopUp,
        loc.deleteLastDigit,
        loc.pinDigitsEntered(2, 4),
      ];

      expect(messages, everyElement(isNotEmpty));
      expect(messages, everyElement(isNot(contains(RegExp(r'\{\w+\}')))));
    }

    expect(AppLocalizations.delegate.isSupported(const Locale('fr')), isTrue);
    expect(AppLocalizations.delegate.isSupported(const Locale('wo')), isFalse);
    expect(
      await AppLocalizations.delegate.load(const Locale('en')),
      isA<AppLocalizations>(),
    );
    expect(
      AppLocalizations.delegate.shouldReload(AppLocalizations.delegate),
      isFalse,
    );
  });

  test('unsupported locales fall back to English', () {
    final loc = AppLocalizations(const Locale('wo'));
    expect(loc.continueLabel, 'Continue');
  });
}
