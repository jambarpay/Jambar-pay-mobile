        loc.paymentSuccessMessage('Le FOOD'),
        loc.partnerRestaurant,
        loc.currentSecretCode,
        loc.newSecretCode,
        loc.confirmation,
        loc.enterYourCurrentCode,
        loc.chooseNewSecretCode,
        loc.enterNewSecretCodeAgain,
        loc.setYourNewSecretCode,
        loc.enterCodeAgain,
        loc.codeMismatch,
        loc.current,
        loc.newLabel,
        loc.confirmationShort,
        loc.pinCode,
