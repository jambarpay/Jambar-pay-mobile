        loc.incorrectSecretCode(2, 'attempts'),
        loc.youCanRetryNow,
        loc.validated,
        loc.active,
        loc.todayAt('12h00'),
        loc.yesterdayAt('12h00'),
        loc.dateTime('01/01/2030', '12h00'),
